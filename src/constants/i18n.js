/* ─── WHY ONLY ENGLISH IS IN HERE ────────────────────────────────────
   Measured: this file was 424 KB of the app's first download — thirteen
   languages sent to every phone so that one of them could be read. It
   was the largest single file the app owned.

   The obvious fix is a dynamic import per language. That does not work
   here: Expo's web export emits the chunks and never fetches them, and
   Metro then fails with "Requiring unknown module". So the twelve other
   languages stopped being modules and became DATA — plain JSON in
   public/i18n/, fetched over HTTP the first time somebody chooses that
   language, and kept afterwards. No bundler is involved, so nothing can
   silently fail to load it.

   English stays compiled in because it is the fallback: t() answers
   from it while another language is still arriving, and on the day the
   network is down it is the difference between an app in English and an
   app showing key names.

   Adding a key: add it here, then run `node scripts/sync-i18n.mjs` —
   which is also what check-i18n verifies, so a forgotten translation
   fails the build rather than shipping. */
